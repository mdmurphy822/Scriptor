//! Host-side contract of the sampling kernels in `kernels/penalty_argmax.cu`:
//! row parameter layout, token bitsets, the seeded uniform generator, launch
//! geometry, and the CPU reference of the temperature / top-k / top-p choice.

use crate::reference::sampling::{GreedyPick, Penalties, argmax_with_margin};

/// Embedded fatbin stem of the sampling kernels.
pub const KERNEL_FILE: &str = "penalty_argmax";
/// Greedy kernel: penalties then argmax with top-2 margin for every row.
pub const KERNEL_PENALTY_ARGMAX: &str = "scriptor_penalty_argmax";
/// Per-row kernel: argmax where temperature is zero, seeded sampling otherwise.
pub const KERNEL_SAMPLE_ROWS: &str = "scriptor_sample_rows";
/// Verification-row kernel: `k + 1` rows per sequence, each seeing the earlier drafts as output.
pub const KERNEL_SAMPLE_ROWS_SPEC: &str = "scriptor_sample_rows_spec";
/// Greedy kernel reading a bf16 logits matrix directly.
pub const KERNEL_PENALTY_ARGMAX_BF16: &str = "scriptor_penalty_argmax_bf16";
/// Per-row kernel reading a bf16 logits matrix directly.
pub const KERNEL_SAMPLE_ROWS_BF16: &str = "scriptor_sample_rows_bf16";
/// Verification-row kernel reading a bf16 logits matrix directly.
pub const KERNEL_SAMPLE_ROWS_SPEC_BF16: &str = "scriptor_sample_rows_spec_bf16";
/// Embedded fatbin stem of the two-stage greedy target selector.
pub const SPLIT_KERNEL_FILE: &str = "penalty_argmax_split";
/// Stage 1 of the split selector: scans row slices into per-virtual-thread top-2 partials.
pub const KERNEL_SPEC_SCAN_BF16: &str = "scriptor_spec_scan_bf16";
/// Stage 2 of the split selector: reduces the partials of each row to a token and margin.
pub const KERNEL_SPEC_REDUCE_BF16: &str = "scriptor_spec_reduce_bf16";
/// Kernel recording accepted tokens into the output bitsets and counts.
pub const KERNEL_MARK_TOKENS: &str = "scriptor_mark_tokens";
/// Largest block of the row kernels; their shared scratch is sized for it.
pub const ROW_BLOCK_THREADS_MAX: u32 = 1024;
/// Smallest block of the row kernels.
pub const ROW_BLOCK_THREADS_MIN: u32 = 128;

/// Per-row parameters read by the device; `repr(C)` layout matches
/// `ScriptorRowParams` in the kernel source (40 bytes, 8-byte aligned).
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct RowParams {
    /// Generator seed of the sequence.
    pub seed: u64,
    /// Repetition penalty; `1.0` disables.
    pub repetition: f32,
    /// Presence penalty; `0.0` disables.
    pub presence: f32,
    /// Frequency penalty; `0.0` disables.
    pub frequency: f32,
    /// Sampling temperature; `0.0` selects argmax.
    pub temperature: f32,
    /// Nucleus mass in `(0, 1]`; `1.0` disables.
    pub top_p: f32,
    /// Number of candidates kept; `0` disables.
    pub top_k: i32,
    /// Number of tokens already generated by the sequence.
    pub step: u32,
    /// Row of the bitset / count pools that belongs to this sequence.
    pub slot: u32,
}

impl RowParams {
    /// Greedy row with no penalties.
    pub fn greedy(slot: u32) -> Self {
        Self {
            seed: 0,
            repetition: 1.0,
            presence: 0.0,
            frequency: 0.0,
            temperature: 0.0,
            top_p: 1.0,
            top_k: 0,
            step: 0,
            slot,
        }
    }

    /// The penalty subset of the parameters.
    pub fn penalties(&self) -> Penalties {
        Penalties {
            repetition: self.repetition,
            presence: self.presence,
            frequency: self.frequency,
        }
    }
}

/// Number of 32-bit words in a vocabulary bitset.
pub fn mask_words(vocab: usize) -> usize {
    vocab.div_ceil(32)
}

/// Prompt and output membership bitsets plus output counts for a pool of
/// sequence slots, in the exact layout the device reads.
#[derive(Debug, Clone)]
pub struct TokenMasks {
    vocab: usize,
    words: usize,
    prompt: Vec<u32>,
    output: Vec<u32>,
    counts: Vec<u32>,
}

impl TokenMasks {
    /// Empty pool of `slots` sequences over a `vocab`-sized id space.
    pub fn new(slots: usize, vocab: usize) -> Self {
        let words = mask_words(vocab);
        Self {
            vocab,
            words,
            prompt: vec![0; slots * words],
            output: vec![0; slots * words],
            counts: vec![0; slots * vocab],
        }
    }

    /// Vocabulary size.
    pub fn vocab(&self) -> usize {
        self.vocab
    }

    /// Words per slot bitset.
    pub fn words(&self) -> usize {
        self.words
    }

    /// Number of slots.
    pub fn slots(&self) -> usize {
        self.prompt.len().checked_div(self.words).unwrap_or(0)
    }

    /// Clears a slot and marks every in-vocabulary id of `prompt`.
    pub fn reset_slot(&mut self, slot: usize, prompt: &[u32]) {
        let w = self.words;
        self.prompt[slot * w..(slot + 1) * w].fill(0);
        self.output[slot * w..(slot + 1) * w].fill(0);
        self.counts[slot * self.vocab..(slot + 1) * self.vocab].fill(0);
        for &t in prompt {
            if (t as usize) < self.vocab {
                self.prompt[slot * w + (t as usize >> 5)] |= 1 << (t & 31);
            }
        }
    }

    /// Records an accepted output token; ids outside the vocabulary are ignored.
    pub fn push_output(&mut self, slot: usize, token: u32) {
        if (token as usize) >= self.vocab {
            return;
        }
        self.output[slot * self.words + (token as usize >> 5)] |= 1 << (token & 31);
        self.counts[slot * self.vocab + token as usize] += 1;
    }

    /// Whether `token` occurs in the slot's prompt.
    pub fn in_prompt(&self, slot: usize, token: u32) -> bool {
        bit(
            &self.prompt[slot * self.words..(slot + 1) * self.words],
            token,
        )
    }

    /// Whether `token` occurs in the slot's output.
    pub fn in_output(&self, slot: usize, token: u32) -> bool {
        bit(
            &self.output[slot * self.words..(slot + 1) * self.words],
            token,
        )
    }

    /// Output occurrence count of `token` in the slot.
    pub fn output_count(&self, slot: usize, token: u32) -> u32 {
        self.counts[slot * self.vocab + token as usize]
    }

    /// Prompt bitset pool as uploaded to the device.
    pub fn prompt_words(&self) -> &[u32] {
        &self.prompt
    }

    /// Output bitset pool as uploaded to the device.
    pub fn output_words(&self) -> &[u32] {
        &self.output
    }

    /// Output count pool as uploaded to the device.
    pub fn count_words(&self) -> &[u32] {
        &self.counts
    }
}

fn bit(words: &[u32], token: u32) -> bool {
    words
        .get(token as usize >> 5)
        .is_some_and(|w| w >> (token & 31) & 1 == 1)
}

/// Applies the slot's penalties to `logits` in place, reading membership from
/// the bitsets and counts exactly as the device does.
pub fn apply_masked_penalties(logits: &mut [f32], masks: &TokenMasks, slot: usize, p: Penalties) {
    for (i, logit) in logits.iter_mut().enumerate() {
        let id = i as u32;
        let in_output = masks.in_output(slot, id);
        if p.repetition != 1.0 && (masks.in_prompt(slot, id) || in_output) {
            *logit = if *logit > 0.0 {
                *logit / p.repetition
            } else {
                *logit * p.repetition
            };
        }
        *logit -= p.frequency * masks.output_count(slot, id) as f32;
        if in_output {
            *logit -= p.presence;
        }
    }
}

/// Uniform in `[0, 1)` from `(seed, step)`: the splitmix64 finalizer, top 24
/// bits. Identical to `scriptor_uniform` on the device.
pub fn uniform(seed: u64, step: u32) -> f32 {
    let mut z = seed.wrapping_add((u64::from(step) + 1).wrapping_mul(0x9E37_79B9_7F4A_7C15));
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^= z >> 31;
    (z >> 40) as u32 as f32 * (1.0 / 16_777_216.0)
}

/// Chooses a token from penalised `logits`: argmax when `temperature <= 0`;
/// otherwise keeps the `top_k` largest values (ties kept), then the smallest
/// set of largest values whose softmax mass reaches `top_p` (ties kept), and
/// draws from the renormalised distribution by inverse CDF in id order at
/// uniform `u`.
pub fn choose_token(logits: &[f32], temperature: f32, top_k: i32, top_p: f32, u: f32) -> u32 {
    if temperature <= 0.0 {
        return argmax_with_margin(logits).token;
    }
    let vocab = logits.len();
    let mut threshold = f32::NEG_INFINITY;
    if top_k > 0 && (top_k as usize) < vocab {
        let mut sorted = logits.to_vec();
        sorted.sort_by(|a, b| b.total_cmp(a));
        threshold = sorted[top_k as usize - 1];
    }
    let max = logits.iter().copied().fold(f32::NEG_INFINITY, f32::max);
    let weight = |v: f32| f64::from(((v - max) * (1.0 / temperature)).exp());
    if top_p < 1.0 {
        let mut kept: Vec<f32> = logits.iter().copied().filter(|&v| v >= threshold).collect();
        kept.sort_by(|a, b| b.total_cmp(a));
        let z: f64 = kept.iter().map(|&v| weight(v)).sum();
        let want = f64::from(top_p) * z;
        let mut acc = 0.0f64;
        let mut cut = kept[kept.len() - 1];
        let mut i = 0;
        while i < kept.len() {
            let v = kept[i];
            while i < kept.len() && kept[i] == v {
                acc += weight(kept[i]);
                i += 1;
            }
            if acc >= want {
                cut = v;
                break;
            }
        }
        threshold = cut;
    }
    let total: f64 = logits
        .iter()
        .filter(|&&v| v >= threshold)
        .map(|&v| weight(v))
        .sum();
    let target = f64::from(u) * total;
    let mut acc = 0.0f64;
    let mut last = 0u32;
    for (i, &v) in logits.iter().enumerate() {
        if v >= threshold {
            acc += weight(v);
            last = i as u32;
            if acc > target {
                return i as u32;
            }
        }
    }
    last
}

/// Full CPU reference of one row: penalties from the slot masks, argmax margin
/// of the penalised row, then the greedy or sampled token.
pub fn process_row(logits: &[f32], masks: &TokenMasks, params: &RowParams) -> GreedyPick {
    let mut row = logits.to_vec();
    apply_masked_penalties(&mut row, masks, params.slot as usize, params.penalties());
    let greedy = argmax_with_margin(&row);
    let token = choose_token(
        &row,
        params.temperature,
        params.top_k,
        params.top_p,
        uniform(params.seed, params.step),
    );
    GreedyPick {
        token,
        margin: greedy.margin,
    }
}

/// Threads per block of a row kernel: the largest power of two (within the block limits) at
/// which `rows` blocks are all resident at once on `sm_count` multiprocessors holding
/// `threads_per_sm` threads each.
pub fn row_block_threads(rows: usize, sm_count: usize, threads_per_sm: usize) -> u32 {
    let per_sm = rows.div_ceil(sm_count.max(1)).max(1);
    let fit = (threads_per_sm / per_sm).clamp(
        ROW_BLOCK_THREADS_MIN as usize,
        ROW_BLOCK_THREADS_MAX as usize,
    );
    1u32 << fit.ilog2()
}

/// Launch geometry of a row kernel: one block per row, sized by [`row_block_threads`].
pub fn row_kernel_launch(
    rows: usize,
    sm_count: usize,
    threads_per_sm: usize,
) -> crate::launch::LaunchDims {
    crate::launch::LaunchDims {
        grid: (rows as u32, 1, 1),
        block: (row_block_threads(rows, sm_count, threads_per_sm), 1, 1),
        shared_bytes: 0,
    }
}

/// Words of one stored top-2 partial: best, index and second.
pub const TOP2_WORDS: usize = 3;
/// Words of the split selector's partial buffer for `rows` rows of full virtual width.
pub const fn split_scratch_words(rows: usize) -> usize {
    let words = rows * 1024 * TOP2_WORDS;
    if words == 0 { 1 } else { words }
}

/// Default largest row count the split selector serves.
pub const SPLIT_MAX_ROWS_DEFAULT: usize = 8;

/// Parameters of the two-stage greedy target selector.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SplitSelect {
    /// Threads per stage-1 block: a power of two from 32 to 1024.
    pub block_threads: u32,
    /// Stage-1 blocks per row, at least 1.
    pub ctas_per_row: u32,
    /// Largest verification row count routed to the selector; larger batches keep the
    /// single-block kernel.
    pub max_rows: usize,
}

impl SplitSelect {
    /// Parses `BLOCKxCTAS` or `BLOCKxCTASxMAXROWS`; `None` for anything malformed or invalid.
    pub fn parse(text: &str) -> Option<Self> {
        let mut parts = text.trim().split('x');
        let block_threads = parts.next()?.trim().parse().ok()?;
        let ctas_per_row = parts.next()?.trim().parse().ok()?;
        let max_rows = match parts.next() {
            Some(v) => v.trim().parse().ok()?,
            None => SPLIT_MAX_ROWS_DEFAULT,
        };
        if parts.next().is_some() {
            return None;
        }
        let select = Self {
            block_threads,
            ctas_per_row,
            max_rows,
        };
        select.is_valid().then_some(select)
    }

    /// Whether the parameters describe a launchable selector.
    pub fn is_valid(&self) -> bool {
        self.block_threads.is_power_of_two()
            && (32..=ROW_BLOCK_THREADS_MAX).contains(&self.block_threads)
            && self.ctas_per_row >= 1
            && self.max_rows >= 1
    }

    /// Launch geometry for `rows` verification rows, or `None` when the selector is invalid or
    /// `rows` is zero or above `max_rows`, in which case the single-block kernel serves them.
    ///
    /// The virtual width is the single-block kernel's block width for `rows`; the stage-1 grid
    /// covers its virtual threads with blocks of at most `block_threads` threads, and stage 2
    /// runs one block of the virtual width per row.
    pub fn geometry(
        &self,
        rows: usize,
        sm_count: usize,
        threads_per_sm: usize,
    ) -> Option<SplitGeometry> {
        if !self.is_valid() || rows == 0 || rows > self.max_rows {
            return None;
        }
        let virtual_width = row_block_threads(rows, sm_count, threads_per_sm);
        let vt_per_cta = virtual_width.div_ceil(self.ctas_per_row);
        let ctas = virtual_width.div_ceil(vt_per_cta);
        let block = self
            .block_threads
            .min(vt_per_cta.next_power_of_two().max(32));
        Some(SplitGeometry {
            virtual_width,
            vt_per_cta,
            scan: crate::launch::LaunchDims {
                grid: (ctas, rows as u32, 1),
                block: (block, 1, 1),
                shared_bytes: 0,
            },
            reduce: crate::launch::LaunchDims {
                grid: (rows as u32, 1, 1),
                block: (virtual_width, 1, 1),
                shared_bytes: 0,
            },
            partial_words: rows * virtual_width as usize * TOP2_WORDS,
        })
    }
}

/// Resolved launch geometry of the split selector for one row count.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SplitGeometry {
    /// Block width of the single-block kernel, which every stride and the reduction keep.
    pub virtual_width: u32,
    /// Consecutive virtual threads scanned by one stage-1 block.
    pub vt_per_cta: u32,
    /// Stage-1 launch: `(ctas, rows)` blocks.
    pub scan: crate::launch::LaunchDims,
    /// Stage-2 launch: one block of `virtual_width` threads per row.
    pub reduce: crate::launch::LaunchDims,
    /// Device words the partial buffer needs.
    pub partial_words: usize,
}

impl SplitGeometry {
    /// The virtual threads scanned by stage-1 block `cta` of a row.
    pub fn virtual_range(&self, cta: u32) -> std::ops::Range<u32> {
        let lo = (cta * self.vt_per_cta).min(self.virtual_width);
        lo..(lo + self.vt_per_cta).min(self.virtual_width)
    }
}

/// Whether every row takes the argmax on the device: exactly the kernel's `temperature <= 0`
/// predicate, so a NaN temperature is not greedy.
pub fn rows_all_greedy<'a>(params: impl IntoIterator<Item = &'a RowParams>) -> bool {
    params.into_iter().all(|p| p.temperature <= 0.0)
}

/// Launch geometry of the token-marking kernel for `n` tokens.
pub fn mark_kernel_launch(n: usize) -> crate::launch::LaunchDims {
    crate::launch::elementwise_launch(n.max(1), 128)
}

