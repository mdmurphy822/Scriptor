#[cfg(feature = "cuda")]
mod device {
    use std::sync::Arc;

    use cudarc::driver::{
        CudaContext, CudaFunction, CudaSlice, CudaStream, DeviceRepr, PushKernelArg,
    };
    use scriptor_cuda::Result;

    use super::{
        KERNEL_FILE, KERNEL_MARK_TOKENS, KERNEL_PENALTY_ARGMAX, KERNEL_PENALTY_ARGMAX_BF16,
        KERNEL_SAMPLE_ROWS, KERNEL_SAMPLE_ROWS_BF16, KERNEL_SAMPLE_ROWS_SPEC,
        KERNEL_SAMPLE_ROWS_SPEC_BF16, KERNEL_SPEC_REDUCE_BF16, KERNEL_SPEC_SCAN_BF16, RowParams,
        SPLIT_KERNEL_FILE, SplitSelect, TOP2_WORDS, mark_kernel_launch, row_kernel_launch,
    };
    use crate::norm::{load_module, to_config};

    // SAFETY: `RowParams` is `repr(C)`, 40 bytes with no padding, and every
    // field is a plain number; it mirrors `ScriptorRowParams` in the kernel source.
    unsafe impl DeviceRepr for RowParams {}

    /// Device partial buffer of the split selector, sized for a row bound.
    pub struct SplitScratch {
        partials: CudaSlice<u32>,
    }

    impl SplitScratch {
        /// Rows of the widest virtual width the buffer holds.
        pub fn rows(&self) -> usize {
            self.partials.len() / (1024 * TOP2_WORDS)
        }
    }

    /// Device launchers of the penalty, argmax and sampling kernels.
    pub struct SamplingKernels {
        penalty_argmax: CudaFunction,
        sample_rows: CudaFunction,
        sample_rows_spec: CudaFunction,
        penalty_argmax_bf16: CudaFunction,
        sample_rows_bf16: CudaFunction,
        sample_rows_spec_bf16: CudaFunction,
        mark_tokens: CudaFunction,
        spec_scan_bf16: CudaFunction,
        spec_reduce_bf16: CudaFunction,
        sm_count: usize,
        threads_per_sm: usize,
    }

    impl SamplingKernels {
        /// Loads the kernels into `ctx`.
        pub fn load(ctx: &Arc<CudaContext>) -> Result<Self> {
            let module = load_module(ctx, KERNEL_FILE)?;
            let split = load_module(ctx, SPLIT_KERNEL_FILE)?;
            Ok(Self {
                penalty_argmax: module.kernel(KERNEL_PENALTY_ARGMAX)?,
                sample_rows: module.kernel(KERNEL_SAMPLE_ROWS)?,
                sample_rows_spec: module.kernel(KERNEL_SAMPLE_ROWS_SPEC)?,
                penalty_argmax_bf16: module.kernel(KERNEL_PENALTY_ARGMAX_BF16)?,
                sample_rows_bf16: module.kernel(KERNEL_SAMPLE_ROWS_BF16)?,
                sample_rows_spec_bf16: module.kernel(KERNEL_SAMPLE_ROWS_SPEC_BF16)?,
                mark_tokens: module.kernel(KERNEL_MARK_TOKENS)?,
                spec_scan_bf16: split.kernel(KERNEL_SPEC_SCAN_BF16)?,
                spec_reduce_bf16: split.kernel(KERNEL_SPEC_REDUCE_BF16)?,
                sm_count: ctx.attribute(
                    cudarc::driver::sys::CUdevice_attribute::CU_DEVICE_ATTRIBUTE_MULTIPROCESSOR_COUNT,
                )? as usize,
                threads_per_sm: ctx.attribute(
                    cudarc::driver::sys::CUdevice_attribute::CU_DEVICE_ATTRIBUTE_MAX_THREADS_PER_MULTIPROCESSOR,
                )? as usize,
            })
        }

        /// Applies each row's penalties to `logits` in place, then writes the
        /// chosen token and the top-2 margin of the penalised row to
        /// `out_tokens` / `out_margins`. With `greedy_only` every row takes
        /// the argmax; otherwise rows with `temperature > 0` are sampled.
        /// `logits` is `[rows, vocab]` fp32; the bitset pools hold `words`
        /// words per slot and `counts` holds `vocab` words per slot.
        #[allow(clippy::too_many_arguments)]
        pub fn choose(
            &self,
            stream: &Arc<CudaStream>,
            greedy_only: bool,
            logits: &mut CudaSlice<f32>,
            rows: usize,
            vocab: usize,
            params: &CudaSlice<RowParams>,
            prompt_bits: &CudaSlice<u32>,
            output_bits: &CudaSlice<u32>,
            counts: &CudaSlice<u32>,
            words: usize,
            out_tokens: &mut CudaSlice<u32>,
            out_margins: &mut CudaSlice<f32>,
        ) -> Result<()> {
            if rows == 0 {
                return Ok(());
            }
            let kernel = if greedy_only {
                &self.penalty_argmax
            } else {
                &self.sample_rows
            };
            let (vocab, words) = (vocab as i32, words as i32);
            // SAFETY: argument order and types match the kernel signature; the
            // caller supplies `rows` logits rows, `rows` parameter/output
            // entries and bitset/count pools covering every referenced slot.
            unsafe {
                stream
                    .launch_builder(kernel)
                    .arg(logits)
                    .arg(&vocab)
                    .arg(params)
                    .arg(prompt_bits)
                    .arg(output_bits)
                    .arg(counts)
                    .arg(&words)
                    .arg(out_tokens)
                    .arg(out_margins)
                    .launch(to_config(row_kernel_launch(
                        rows,
                        self.sm_count,
                        self.threads_per_sm,
                    )))?;
            }
            Ok(())
        }

        /// Chooses a token for each of `seqs * (k + 1)` verification rows of
        /// `logits` (`[rows, vocab]` fp32, `k + 1` consecutive rows per sequence).
        /// Row `j` of a sequence applies that sequence's penalties as if the first
        /// `j` of its `k` drafts (`drafts`, `[seqs, k]`) were already emitted and
        /// samples at step `params[seq].step + j`; `params` holds one entry per
        /// sequence. Rows with `temperature <= 0` take the argmax.
        #[allow(clippy::too_many_arguments)]
        pub fn choose_spec(
            &self,
            stream: &Arc<CudaStream>,
            logits: &mut CudaSlice<f32>,
            seqs: usize,
            k: usize,
            vocab: usize,
            params: &CudaSlice<RowParams>,
            prompt_bits: &CudaSlice<u32>,
            output_bits: &CudaSlice<u32>,
            counts: &CudaSlice<u32>,
            words: usize,
            drafts: &CudaSlice<u32>,
            out_tokens: &mut CudaSlice<u32>,
            out_margins: &mut CudaSlice<f32>,
        ) -> Result<()> {
            let rows = seqs * (k + 1);
            if rows == 0 {
                return Ok(());
            }
            let (vocab, words, k, q) = (vocab as i32, words as i32, k as i32, k as i32 + 1);
            // SAFETY: argument order and types match the kernel signature; the
            // caller supplies `rows` logits rows, `seqs` parameter entries,
            // `[seqs, k]` drafts, `rows` outputs and pools covering every slot.
            unsafe {
                stream
                    .launch_builder(&self.sample_rows_spec)
                    .arg(logits)
                    .arg(&vocab)
                    .arg(params)
                    .arg(prompt_bits)
                    .arg(output_bits)
                    .arg(counts)
                    .arg(&words)
                    .arg(drafts)
                    .arg(&k)
                    .arg(&q)
                    .arg(out_tokens)
                    .arg(out_margins)
                    .launch(to_config(row_kernel_launch(
                        rows,
                        self.sm_count,
                        self.threads_per_sm,
                    )))?;
            }
            Ok(())
        }

        /// As [`Self::choose`] over a bf16 `[rows, vocab]` logits matrix that is read
        /// directly and left unmodified; the result equals widening the matrix to fp32
        /// and calling [`Self::choose`].
        #[allow(clippy::too_many_arguments)]
        pub fn choose_bf16(
            &self,
            stream: &Arc<CudaStream>,
            greedy_only: bool,
            logits: &CudaSlice<u16>,
            rows: usize,
            vocab: usize,
            params: &CudaSlice<RowParams>,
            prompt_bits: &CudaSlice<u32>,
            output_bits: &CudaSlice<u32>,
            counts: &CudaSlice<u32>,
            words: usize,
            out_tokens: &mut CudaSlice<u32>,
            out_margins: &mut CudaSlice<f32>,
        ) -> Result<()> {
            if rows == 0 {
                return Ok(());
            }
            let kernel = if greedy_only {
                &self.penalty_argmax_bf16
            } else {
                &self.sample_rows_bf16
            };
            let (vocab, words) = (vocab as i32, words as i32);
            // SAFETY: argument order and types match the kernel signature; the
            // caller supplies `rows` logits rows, `rows` parameter/output
            // entries and bitset/count pools covering every referenced slot.
            unsafe {
                stream
                    .launch_builder(kernel)
                    .arg(logits)
                    .arg(&vocab)
                    .arg(params)
                    .arg(prompt_bits)
                    .arg(output_bits)
                    .arg(counts)
                    .arg(&words)
                    .arg(out_tokens)
                    .arg(out_margins)
                    .launch(to_config(row_kernel_launch(
                        rows,
                        self.sm_count,
                        self.threads_per_sm,
                    )))?;
            }
            Ok(())
        }

        /// As [`Self::choose_spec`] over a bf16 logits matrix that is read directly and
        /// left unmodified.
        #[allow(clippy::too_many_arguments)]
        pub fn choose_spec_bf16(
            &self,
            stream: &Arc<CudaStream>,
            logits: &CudaSlice<u16>,
            seqs: usize,
            k: usize,
            vocab: usize,
            params: &CudaSlice<RowParams>,
            prompt_bits: &CudaSlice<u32>,
            output_bits: &CudaSlice<u32>,
            counts: &CudaSlice<u32>,
            words: usize,
            drafts: &CudaSlice<u32>,
            out_tokens: &mut CudaSlice<u32>,
            out_margins: &mut CudaSlice<f32>,
        ) -> Result<()> {
            let rows = seqs * (k + 1);
            if rows == 0 {
                return Ok(());
            }
            let (vocab, words, k, q) = (vocab as i32, words as i32, k as i32, k as i32 + 1);
            // SAFETY: argument order and types match the kernel signature; the
            // caller supplies `rows` logits rows, `seqs` parameter entries,
            // `[seqs, k]` drafts, `rows` outputs and pools covering every slot.
            unsafe {
                stream
                    .launch_builder(&self.sample_rows_spec_bf16)
                    .arg(logits)
                    .arg(&vocab)
                    .arg(params)
                    .arg(prompt_bits)
                    .arg(output_bits)
                    .arg(counts)
                    .arg(&words)
                    .arg(drafts)
                    .arg(&k)
                    .arg(&q)
                    .arg(out_tokens)
                    .arg(out_margins)
                    .launch(to_config(row_kernel_launch(
                        rows,
                        self.sm_count,
                        self.threads_per_sm,
                    )))?;
            }
            Ok(())
        }

        /// Allocates the partial buffer of the split selector for up to `max_rows` rows.
        pub fn alloc_split_scratch(
            &self,
            stream: &Arc<CudaStream>,
            max_rows: usize,
        ) -> Result<SplitScratch> {
            Ok(SplitScratch {
                partials: stream.alloc_zeros::<u32>(super::split_scratch_words(max_rows))?,
            })
        }

        /// As [`Self::choose_spec_bf16`] through the two-stage selector, which reproduces the
        /// single-block kernel's tokens and margins bit for bit on rows whose temperature is
        /// not positive. Every row must be greedy; the caller decides that. Returns `false`
        /// without launching when the selector has no geometry for `seqs * (k + 1)` rows or
        /// `scratch` is too small, in which case the caller uses the single-block kernel.
        #[allow(clippy::too_many_arguments)]
        pub fn choose_spec_bf16_split(
            &self,
            stream: &Arc<CudaStream>,
            select: &SplitSelect,
            scratch: &mut SplitScratch,
            logits: &CudaSlice<u16>,
            seqs: usize,
            k: usize,
            vocab: usize,
            params: &CudaSlice<RowParams>,
            prompt_bits: &CudaSlice<u32>,
            output_bits: &CudaSlice<u32>,
            counts: &CudaSlice<u32>,
            words: usize,
            drafts: &CudaSlice<u32>,
            out_tokens: &mut CudaSlice<u32>,
            out_margins: &mut CudaSlice<f32>,
        ) -> Result<bool> {
            let rows = seqs * (k + 1);
            let Some(geometry) = select.geometry(rows, self.sm_count, self.threads_per_sm) else {
                return Ok(false);
            };
            if geometry.partial_words > scratch.partials.len() {
                return Ok(false);
            }
            let (vocab, words, k, q) = (vocab as i32, words as i32, k as i32, k as i32 + 1);
            let (virtual_width, vt_per_cta) =
                (geometry.virtual_width as i32, geometry.vt_per_cta as i32);
            // SAFETY: argument order and types match the kernel signatures; the caller supplies
            // `rows` logits rows, `seqs` parameter entries, `[seqs, k]` drafts, `rows` outputs
            // and pools covering every slot, and the scratch holds `rows * virtual_width`
            // partials of three words.
            unsafe {
                stream
                    .launch_builder(&self.spec_scan_bf16)
                    .arg(logits)
                    .arg(&vocab)
                    .arg(params)
                    .arg(prompt_bits)
                    .arg(output_bits)
                    .arg(counts)
                    .arg(&words)
                    .arg(drafts)
                    .arg(&k)
                    .arg(&q)
                    .arg(&virtual_width)
                    .arg(&vt_per_cta)
                    .arg(&mut scratch.partials)
                    .launch(to_config(geometry.scan))?;
                stream
                    .launch_builder(&self.spec_reduce_bf16)
                    .arg(&scratch.partials)
                    .arg(out_tokens)
                    .arg(out_margins)
                    .launch(to_config(geometry.reduce))?;
            }
            Ok(true)
        }

        /// Whether the split selector launches for `rows` verification rows with a scratch
        /// of `scratch_rows` rows of full virtual width.
        pub fn split_serves(&self, select: &SplitSelect, rows: usize, scratch_rows: usize) -> bool {
            select
                .geometry(rows, self.sm_count, self.threads_per_sm)
                .is_some_and(|g| g.partial_words <= scratch_rows * 1024 * TOP2_WORDS)
        }

        /// Records `tokens[i]` as output of `slots[i]`: sets the output bit and
        /// increments the output count. Ids outside the vocabulary are ignored.
        #[allow(clippy::too_many_arguments)]
        pub fn mark_tokens(
            &self,
            stream: &Arc<CudaStream>,
            output_bits: &mut CudaSlice<u32>,
            counts: &mut CudaSlice<u32>,
            slots: &CudaSlice<u32>,
            tokens: &CudaSlice<u32>,
            n: usize,
            words: usize,
            vocab: usize,
        ) -> Result<()> {
            if n == 0 {
                return Ok(());
            }
            let (n, words, vocab) = (n as i32, words as i32, vocab as i32);
            // SAFETY: argument order and types match the kernel signature;
            // `slots` and `tokens` hold `n` entries and the pools cover every
            // referenced slot.
            unsafe {
                stream
                    .launch_builder(&self.mark_tokens)
                    .arg(output_bits)
                    .arg(counts)
                    .arg(slots)
                    .arg(tokens)
                    .arg(&n)
                    .arg(&words)
                    .arg(&vocab)
                    .launch(to_config(mark_kernel_launch(n as usize)))?;
            }
            Ok(())
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::reference::sampling::apply_penalties;

    const SMS: usize = 48;
    const TPS: usize = 1536;

    fn select(block: u32, ctas: u32) -> SplitSelect {
        SplitSelect {
            block_threads: block,
            ctas_per_row: ctas,
            max_rows: SPLIT_MAX_ROWS_DEFAULT,
        }
    }

    #[test]
    fn split_partitions_every_virtual_thread_exactly_once() {
        for rows in 1..=8usize {
            for block in [32u32, 128, 256, 1024] {
                for ctas in [1u32, 2, 3, 4, 7, 8, 16, 1024, 5000] {
                    let g = select(block, ctas)
                        .geometry(rows, SMS, TPS)
                        .expect("geometry");
                    let mut seen = vec![0u32; g.virtual_width as usize];
                    for cta in 0..g.scan.grid.0 {
                        for t in g.virtual_range(cta) {
                            seen[t as usize] += 1;
                        }
                    }
                    assert!(seen.iter().all(|&n| n == 1), "rows {rows} {block}x{ctas}");
                    assert!(g.scan.grid.0 <= ctas.max(1));
                    assert_eq!(g.scan.grid.1 as usize, rows);
                    assert_eq!(g.reduce.block.0, g.virtual_width);
                    assert_eq!(g.reduce.grid.0 as usize, rows);
                    assert!(g.scan.block.0 <= block.max(32));
                    assert_eq!(g.partial_words, rows * g.virtual_width as usize * 3);
                }
            }
        }
    }

    #[test]
    fn split_keeps_the_single_block_virtual_width() {
        for rows in 1..=8usize {
            let g = select(128, 8).geometry(rows, SMS, TPS).expect("geometry");
            assert_eq!(
                g.virtual_width,
                row_kernel_launch(rows, SMS, TPS).block.0,
                "rows {rows}"
            );
        }
        let g = select(256, 4).geometry(4, SMS, TPS).expect("geometry");
        assert_eq!((g.virtual_width, g.vt_per_cta), (1024, 256));
        assert_eq!(g.scan.grid, (4, 4, 1));
        assert_eq!(g.scan.block.0, 256);
    }

    #[test]
    fn split_falls_back_outside_its_row_bound_or_when_invalid() {
        let s = select(128, 8);
        assert!(s.geometry(0, SMS, TPS).is_none());
        assert!(s.geometry(SPLIT_MAX_ROWS_DEFAULT + 1, SMS, TPS).is_none());
        assert!(s.geometry(SPLIT_MAX_ROWS_DEFAULT, SMS, TPS).is_some());
        for bad in [
            select(100, 4),
            select(2048, 4),
            select(0, 4),
            select(128, 0),
        ] {
            assert!(!bad.is_valid());
            assert!(bad.geometry(2, SMS, TPS).is_none());
        }
    }

    #[test]
    fn split_select_parses_only_valid_specs() {
        assert_eq!(SplitSelect::parse("128x8"), Some(select(128, 8)));
        assert_eq!(
            SplitSelect::parse(" 256x4x2 "),
            Some(SplitSelect {
                block_threads: 256,
                ctas_per_row: 4,
                max_rows: 2
            })
        );
        for bad in [
            "",
            "128",
            "128x",
            "x8",
            "100x8",
            "128x0",
            "128x8x0",
            "128x8x2x1",
            "ax8",
        ] {
            assert_eq!(SplitSelect::parse(bad), None, "{bad:?}");
        }
    }

    #[test]
    fn greedy_routing_matches_the_device_predicate() {
        let greedy = RowParams::greedy(0);
        let mut sampled = RowParams::greedy(1);
        sampled.temperature = 0.7;
        let mut negative = RowParams::greedy(2);
        negative.temperature = -1.0;
        let mut nan = RowParams::greedy(3);
        nan.temperature = f32::NAN;
        assert!(rows_all_greedy(&[greedy, negative]));
        assert!(rows_all_greedy(&[]));
        assert!(!rows_all_greedy(&[greedy, sampled]));
        assert!(!rows_all_greedy(&[nan]));
        assert!(!rows_all_greedy(&[sampled, greedy]));
    }

    #[test]
    fn row_params_layout() {
        assert_eq!(std::mem::size_of::<RowParams>(), 40);
        assert_eq!(std::mem::align_of::<RowParams>(), 8);
    }

    #[test]
    fn masked_equals_id_list_reference() {
        let vocab = 70;
        let logits: Vec<f32> = (0..vocab).map(|i| (i as f32 - 30.0) * 0.37).collect();
        let prompt = [3u32, 40, 69, 500];
        let output = [5u32, 5, 40, 41];
        let mut masks = TokenMasks::new(2, vocab);
        masks.reset_slot(1, &prompt);
        for &t in &output {
            masks.push_output(1, t);
        }
        let p = Penalties {
            repetition: 1.3,
            presence: 0.4,
            frequency: 0.2,
        };
        let mut a = logits.clone();
        apply_masked_penalties(&mut a, &masks, 1, p);
        let mut b = logits;
        apply_penalties(&mut b, &prompt, &output, p);
        assert_eq!(a, b);
    }

    #[test]
    fn uniform_is_in_unit_interval_and_varies() {
        let a = uniform(7, 0);
        let b = uniform(7, 1);
        assert!((0.0..1.0).contains(&a) && (0.0..1.0).contains(&b));
        assert_ne!(a, b);
        assert_eq!(uniform(7, 0), a);
    }

    #[test]
    fn top_k_one_is_argmax() {
        let l = [0.1, 3.0, 2.9, -1.0];
        for step in 0..20 {
            assert_eq!(choose_token(&l, 1.0, 1, 1.0, uniform(1, step)), 1);
        }
    }

    #[test]
    fn tiny_top_p_keeps_only_the_best() {
        let l = [0.1, 3.0, 2.9, -1.0];
        for step in 0..20 {
            assert_eq!(choose_token(&l, 1.0, 0, 1e-5, uniform(9, step)), 1);
        }
    }

    #[test]
    fn top_p_cuts_the_tail() {
        let l = [10.0, 10.0, 0.0, 0.0];
        for step in 0..50 {
            let t = choose_token(&l, 1.0, 0, 0.9, uniform(3, step));
            assert!(t < 2);
        }
    }

    #[test]
    fn sampling_follows_the_distribution() {
        let l = [0.0f32, (3.0f32).ln()];
        let ones = (0..4000)
            .filter(|&s| choose_token(&l, 1.0, 0, 1.0, uniform(42, s)) == 1)
            .count();
        let frac = ones as f32 / 4000.0;
        assert!((frac - 0.75).abs() < 0.03, "{frac}");
    }

    #[test]
    fn seeded_choice_is_reproducible() {
        let l: Vec<f32> = (0..50).map(|i| ((i * 7) % 13) as f32 * 0.3).collect();
        let a = choose_token(&l, 0.8, 10, 0.9, uniform(5, 3));
        let b = choose_token(&l, 0.8, 10, 0.9, uniform(5, 3));
        assert_eq!(a, b);
    }

    #[test]
    fn zero_temperature_ignores_top_filters() {
        let l = [1.0, 5.0, 4.0];
        assert_eq!(choose_token(&l, 0.0, 1, 1e-5, 0.99), 1);
    }

    #[test]
    fn process_row_greedy_matches_reference_with_margin() {
        let mut masks = TokenMasks::new(1, 4);
        masks.reset_slot(0, &[0]);
        let mut p = RowParams::greedy(0);
        p.repetition = 2.0;
        let pick = process_row(&[3.0, 2.0, 0.0, 0.0], &masks, &p);
        assert_eq!(pick.token, 1);
        assert!((pick.margin - 0.5).abs() < 1e-6);
    }
}
